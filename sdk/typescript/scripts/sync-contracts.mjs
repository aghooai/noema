#!/usr/bin/env node
// Copies the vendored contract surface (src/noema/contracts/_vendor) into the SDK and regenerates the wire types
// from the bundled OpenAPI document (IMPL-035, spec-08 §10.3). `--check` writes nothing and exits 1 on any drift.
//
// - src/types.ts, src/sdk.ts: byte copies (the public types; the client implements sdk.ts).
// - src/openai-compat.ts: a copy whose doc comment names the OpenAI endpoint by path only (the repo's forbidden-endpoint
//   scan allows that host name in the canonical vendored file alone).
// - test/sdk-usage.check.ts: the contract's compile-time usage checks, with the two imports pointed at the
//   implementation (src/index) instead of the declaration-only sdk.ts.
// - src/generated/openapi.d.ts: openapi-typescript@7.13.0 --default-non-nullable false.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = resolve(SDK, "../..");
const VENDOR = join(REPO, "src/noema/contracts/_vendor");
const BUNDLE = join(REPO, "src/noema/contracts/build/openapi.bundled.yaml");

const OPENAI_URL = /https:\/\/api\.openai\.com(\/v1\/decisions)/g;
const GENERATED_HEADER = "// Generated by scripts/sync-contracts.mjs (openapi-typescript 7.13.0). Do not edit.\n";

/** Each target: [path relative to the SDK, function returning its expected content]. */
export function vendoredTargets() {
  const read = (name) => readFileSync(join(VENDOR, name), "utf8");
  return [
    ["src/types.ts", () => read("types.ts")],
    ["src/sdk.ts", () => read("sdk.ts")],
    ["src/openai-compat.ts", () => read("openai-compat.ts").replace(OPENAI_URL, "the OpenAI Decisions endpoint ($1)")],
    [
      "test/sdk-usage.check.ts",
      () =>
        read("sdk-usage.check.ts")
          .replace('from "./sdk";', 'from "../src/index";')
          .replace('from "./openai-compat";', 'from "../src/openai-compat";'),
    ],
  ];
}

export async function generatedWireTypes() {
  const ast = await openapiTS(new URL(`file://${BUNDLE}`), { defaultNonNullable: false });
  return GENERATED_HEADER + astToString(ast);
}

/** Returns the SDK-relative paths whose content differs from the expected content (writes them unless `check`). */
export async function sync({ check }) {
  const targets = [...vendoredTargets(), ["src/generated/openapi.d.ts", generatedWireTypes]];
  const drift = [];
  for (const [rel, expected] of targets) {
    const path = join(SDK, rel);
    const want = await expected();
    let have = null;
    try {
      have = readFileSync(path, "utf8");
    } catch {
      have = null;
    }
    if (have !== want) {
      drift.push(rel);
      if (!check) writeFileSync(path, want);
    }
  }
  return drift;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const drift = await sync({ check });
  if (check && drift.length > 0) {
    console.error(`contract drift (run npm run sync): ${drift.join(", ")}`);
    process.exit(1);
  }
  console.log(drift.length === 0 ? "contracts in sync" : `updated: ${drift.join(", ")}`);
}
