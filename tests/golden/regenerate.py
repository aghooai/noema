"""Regenerate every golden file: `PYTHONPATH=. python -m tests.golden.regenerate` (from the repo root).

Writes `tests/golden/sse/Gnn_<slug>.yaml` (the SSE fixtures) and the wire-request goldens under
`tests/golden/{decision,generation}_requests/`. `tests/contract_internal/test_golden_fixtures.py` fails when a
committed file differs from what the builders produce.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Final

import orjson
import yaml

from .sse_builder import build_all
from .wire import WIRE_DIRS, build_wire_goldens

SSE_DIR: Final = Path(__file__).with_name("sse")
HEADER: Final = "# Generated by tests/golden/regenerate.py from tests/golden/sse_builder.py. Do not edit by hand.\n"


def slug(title: str) -> str:
    """A file-name slug of a title, cut at a word boundary (<= 32 characters)."""
    out = ""
    for word in re.sub(r"[^a-z0-9]+", " ", title.lower()).split():
        if len(out) + len(word) + 1 > 32:
            break
        out = f"{out}_{word}" if out else word
    return out


def sse_files() -> dict[Path, str]:
    """Path -> YAML text of every SSE fixture."""
    out: dict[Path, str] = {}
    for fx in build_all():
        text = yaml.safe_dump(fx, sort_keys=False, allow_unicode=True, width=120)
        out[SSE_DIR / f"{fx['id']}_{slug(fx['title'])}.yaml"] = HEADER + text
    return out


def wire_files() -> dict[Path, str]:
    """Path -> JSON text of every wire-request golden."""
    out: dict[Path, str] = {}
    for kind, cases in build_wire_goldens().items():
        for case in cases:
            body: Any = orjson.dumps(case, option=orjson.OPT_INDENT_2 | orjson.OPT_SORT_KEYS).decode() + "\n"
            out[WIRE_DIRS[kind] / f"{case['name']}.json"] = body
    return out


def all_files() -> dict[Path, str]:
    return {**sse_files(), **wire_files()}


def main() -> None:
    files = all_files()
    for directory in {p.parent for p in files}:
        directory.mkdir(parents=True, exist_ok=True)
        for stale in directory.glob("*.yaml" if directory == SSE_DIR else "*.json"):
            if stale not in files:
                stale.unlink()
    for path, text in files.items():
        path.write_text(text)
    print(f"wrote {len(files)} golden files")


if __name__ == "__main__":
    main()
